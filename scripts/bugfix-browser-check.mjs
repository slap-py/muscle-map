import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium} from '@playwright/test';
import { viewerUrl } from './browser-url.mjs';
const browser = await chromium.launch({channel:'msedge',headless:true});
const checks=[],errors=[];
const base=viewerUrl().replace(/#.*$/, '');
const check=(ok,text)=>{assert(ok,text);checks.push(text);};
const page=await browser.newPage({viewport:{width:1280,height:720},reducedMotion:'reduce'});
page.on('pageerror',e=>errors.push(e.message));
const open=async hash=>{await page.goto(base+'#'+hash);await page.locator('#loading').waitFor({state:'detached',timeout:90000});};
const select=async(q,id)=>{await page.locator('#search').fill(q);await page.locator(`.structure-row[data-id="${id}"]`).click();};
const listCount=async()=>{const text=await page.locator('#list-count').textContent();const match=text?.match(/Showing (\d+) of (\d+)/);return match ? {shown:Number(match[1]),total:Number(match[2]),text} : null;};
try {
  for(const size of [{width:1280,height:720},{width:375,height:812}]) {
    await page.setViewportSize(size);
    for(const [hash,label] of [['/','Home'],['/how-it-works','How it works'],['/browser','Browser']]) {
      await open(hash); await page.locator('.site-footer a').click();
      await page.waitForURL('**/#/credits');
      check(await page.locator('.credits-main h1').evaluate(el=>el.getBoundingClientRect().top>=0),'Credits starts at top from '+label+' at '+size.width);
      check(await page.locator('.credits-back').getAttribute('href')==='#'+hash,'Credits returns to '+label+' at '+size.width);
      check(await page.locator('.site-footer').count()===1,'Shared footer on Credits at '+size.width);
    }
    check(await page.locator('a[href$="manifest.json"]').count()===7,'Credits links to all model manifests at '+size.width);
  }
  await page.setViewportSize({width:1280,height:720});
  await open('/regions?region=lower-leg&region=right-upper-leg');
  const combinedCount=await listCount();
  check(!!combinedCount && combinedCount.shown===combinedCount.total && combinedCount.total>0,'Combined view lists every browsable structure by default');
  await page.locator('#search').fill('cartilage');
  check(await page.locator('.structure-row').count()>0,'Cartilage searchable by default');
  await page.locator('#clear-filters').click();
  const clearedCount=await listCount();
  check(!!clearedCount && clearedCount.shown===clearedCount.total && clearedCount.total===combinedCount?.total,'Clear filters includes all browsable structures including skin');
  await select('rectus femoris','right-upper-leg:rectus-femoris');
  await page.locator('#viewport').waitFor({state:'visible'});
  await page.waitForFunction(()=>Number(document.querySelector('#viewport').dataset.loadedMuscles)>20,undefined,{timeout:90000});
  await page.locator('.attachment-details summary').first().click();
  const attachment=page.locator('.connection-focus').filter({hasText:'Hip bone'}).first();
  await attachment.click();
  const hint=await page.locator('#layer-hint').evaluate(el=>{const r=el.getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight;});
  check(hint,'Attachment restore hint is visible at laptop height');
  await page.screenshot({path:'validation/bugfix-attachment.png'});
  check(await page.locator('.attachment-details').getAttribute('open')!==null,'Attachments stays open after focus');
  check(await page.locator('.connection-focus[aria-pressed="true"]').count()===1,'Attachment focused');
  await page.locator('.connection-focus[aria-pressed="true"]').click();
  check(await page.locator('.attachment-details').getAttribute('open')!==null,'Attachments stays open after returning');
  await select('sartorius','right-upper-leg:sartorius');
  check(!/\.ol|\.el|origin · Origin/i.test(await page.locator('.attachment-details').textContent()),'Attachment descriptions omit internal object names and repeated labels');
  const heights=await page.evaluate(()=>({details:document.querySelector('#details').clientHeight,layers:document.querySelector('.layer-section').clientHeight}));
  console.log('Panel heights',heights);
  check(heights.details>=240 && heights.details>heights.layers,'Laptop details has useful space');
  await page.screenshot({path:'validation/bugfix-laptop.png'});
  await page.locator('#highlight-connections').click();await page.locator('#clear').click();
  check(!(await page.locator('#highlight-connections').isDisabled()) && await page.locator('#highlight-connections').getAttribute('aria-pressed')==='false','Highlight connections clears and stays available with no selection');
  await select('tibia','lower-leg:tibia');await page.locator('#search').fill('soleus');
  check(await page.locator('.structure-row[data-id="lower-leg:tibia"]').count()===0,'Selected Tibia respects Soleus search');
  await page.locator('.structure-row[data-id="lower-leg:soleus-distal"]').click();
  check((await page.locator('.structure-tag').textContent()).includes('Lower leg'),'Soleus is tagged Lower leg');
  await page.setViewportSize({width:375,height:812});
  await open('/regions?region=left-lower-leg&region=left-upper-leg');
  await select('sartorius','left-upper-leg:sartorius');
  const mobile=await page.evaluate(()=>({top:document.querySelector('#details h2').getBoundingClientRect().top,list:document.querySelector('.atlas-scroll').clientHeight,viewport:innerHeight,width:document.documentElement.scrollWidth}));
  console.log('Mobile layout',mobile);
  check(mobile.top>=100 && mobile.top<mobile.viewport-100,'Mobile selection brings details into view');
  check(mobile.list>=280,'Mobile list has usable height');
  check(mobile.width===375,'Mobile has no horizontal overflow');
  await page.screenshot({path:'validation/bugfix-mobile.png'});
  await page.locator('#about').evaluate(el=>el.click());
  const overview=await page.locator('#about-panel-overview').textContent();
  check(/\d+ browsable structures/.test(overview) && overview.includes('tibia/fibula'),'Combined About explains total and shared bone context');
  check(!overview.includes('region picker') && /skin/i.test(overview),'About describes available skin controls');
  await page.locator('.dialog-close').click();
  await page.locator('#reset').evaluate(el=>el.click());
  const resetCount=await listCount();
  check(await page.locator('#search').inputValue()==='' && !!resetCount && resetCount.shown===resetCount.total,'Reset restores filters and clears search');
  await page.locator('#search').fill('zzzz');
  check(!(await page.locator('.atlas-scroll').textContent()).includes('talus'),'Empty-state help is region independent');
  await page.setViewportSize({width:1280,height:720});
  await open('/left-upper-leg');
  await page.locator('#clear-filters').evaluate(el=>el.click());
  const upperCount=await listCount();
  check(!!upperCount && upperCount.shown===upperCount.total && upperCount.total>0,'Upper-leg total matches available filters');
  await open('/browser');
  await page.locator('[data-section="right-hip-leg"]').focus();
  const tooltip=await page.locator('.tip-counts').textContent();
  check(/\d+/.test(tooltip) && tooltip.includes('veins') && tooltip.includes('tendons') && tooltip.includes('fascia') && tooltip.includes('cartilage') && tooltip.includes('skin'),'Tooltip includes all browsable categories');
  check(await page.locator('.site-footer a span').count()===0,'Internal Credits link has no external-link arrow');
  await page.goto(base+'#/');
  await page.screenshot({path:'validation/bugfix-home.png',fullPage:true});
  check(!errors.length,'No browser runtime errors');
  await fs.writeFile('validation/bugfix-check.json',JSON.stringify({checks,errors},null,2));
  console.log(JSON.stringify({checks,errors},null,2));
} finally {await browser.close();}
